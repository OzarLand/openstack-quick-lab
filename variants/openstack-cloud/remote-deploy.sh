#!/usr/bin/env bash
# Runs on the lab VM (copied and started by deploy.sh). Deploys OpenStack all-in-one with Kolla-Ansible.
# Every step is timed and leaves a marker in ~/.quicklab: a new run skips the steps already done.
set -euo pipefail
: "${KOLLA_ANSIBLE_VERSION:?}" "${ANSIBLE_CORE_VERSION:?}" "${LAB_EXT_CIDR:?}"
HTTPS_PROXY="${HTTPS_PROXY:-}"; NTP_SERVER="${NTP_SERVER:-}"; APT_HTTPS="${APT_HTTPS:-no}"
DOCKER_REGISTRY="${DOCKER_REGISTRY:-}"; OPENSTACK_TAG="${OPENSTACK_TAG:-}"
M=~/.quicklab; mkdir -p "$M"; VENV=~/kolla-venv; INV=~/all-in-one
# kolla-ansible runs ansible-galaxy and ansible-playbook from PATH: the virtual environment comes first.
export PATH="$VENV/bin:$PATH"
trap 'echo "   FAILED at line $LINENO: $BASH_COMMAND"' ERR
IFACE=$(ip -4 route show default | awk '{print $5; exit}'); ADDR=$(ip -4 -o addr show "$IFACE" | awk '{print $4}' | cut -d/ -f1)
MTU=$(cat /sys/class/net/"$IFACE"/mtu)
read -r EXT_GW EXT_START EXT_END EXT_PREFIX < <(python3 -c "import ipaddress as i; n=i.ip_network('$LAB_EXT_CIDR'); h=list(n.hosts()); print(h[0], h[99], h[198], n.prefixlen)")
PX=(); [ -n "$HTTPS_PROXY" ] && PX=(env "https_proxy=$HTTPS_PROXY" "http_proxy=$HTTPS_PROXY")
NOPX="localhost,127.0.0.1,$ADDR,$(hostname)${DOCKER_REGISTRY:+,${DOCKER_REGISTRY%%:*}}"

step() { # step <name> <description> <function>
  if [ -f "$M/done-$1" ]; then echo "== $2: already done ($(cat "$M/done-$1") s)"; return; fi
  echo "== $2"; local t0; t0=$(date +%s); "$3"; echo $(( $(date +%s)-t0 )) > "$M/done-$1"; echo "   done in $(cat "$M/done-$1") s"
}
kolla() { # kolla <command> [options]: runs kolla-ansible, keeps the log, shows the failures
  local log="$M/kolla-$1.log"
  if ! "$VENV/bin/kolla-ansible" "$@" -i "$INV" > "$log" 2>&1; then
    grep -E '^fatal' -A8 "$log" | grep -v '\.\.\.ignoring' | head -40; tail -3 "$log"; echo "kolla-ansible $1 failed: full log in $log"; return 1
  fi; tail -2 "$log" | head -1
}

prepare_host() {
  # Automatic upgrades off: they once upgraded libc6 and systemd in the middle of a deploy.
  sudo systemctl disable --now unattended-upgrades apt-daily.timer apt-daily-upgrade.timer >/dev/null 2>&1 || true
  printf 'APT::Periodic::Update-Package-Lists "0";\nAPT::Periodic::Unattended-Upgrade "0";\n' | sudo tee /etc/apt/apt.conf.d/20auto-upgrades >/dev/null
  if [ -n "$HTTPS_PROXY" ]; then
    printf 'Acquire::http::Proxy "%s";\nAcquire::https::Proxy "%s";\n' "$HTTPS_PROXY" "$HTTPS_PROXY" | sudo tee /etc/apt/apt.conf.d/90proxy >/dev/null
  fi
  if [ "$APT_HTTPS" = yes ]; then
    sudo sed -i 's#http://[^ ]*ubuntu.com/ubuntu/\?#https://archive.ubuntu.com/ubuntu/#' /etc/apt/sources.list.d/ubuntu.sources
  fi
  if [ -n "$NTP_SERVER" ]; then
    sudo mkdir -p /etc/systemd/timesyncd.conf.d; printf '[Time]\nNTP=%s\n' "$NTP_SERVER" | sudo tee /etc/systemd/timesyncd.conf.d/90-quicklab.conf >/dev/null
    sudo systemctl restart systemd-timesyncd
  fi
  for _ in $(seq 1 30); do [ "$(timedatectl show -p NTPSynchronized --value)" = yes ] && break; sleep 5; done
  echo "   clock synchronised: $(timedatectl show -p NTPSynchronized --value)"
  sudo apt-get update -q >/dev/null
  sudo DEBIAN_FRONTEND=noninteractive NEEDRESTART_MODE=a apt-get install -y -q git python3-dev python3-venv libffi-dev gcc libssl-dev libdbus-glib-1-dev >/dev/null 2>&1
  # The lab's external network: a veth pair. veth1 goes to Neutron's br-ex, veth0 is its gateway on the host.
  printf '[NetDev]\nName=veth0\nKind=veth\n[Peer]\nName=veth1\n' | sudo tee /etc/systemd/network/25-quicklab-veth.netdev >/dev/null
  printf '[Match]\nName=veth0\n[Network]\nAddress=%s/%s\nLinkLocalAddressing=no\n' "$EXT_GW" "$EXT_PREFIX" | sudo tee /etc/systemd/network/25-quicklab-veth0.network >/dev/null
  printf '[Match]\nName=veth1\n[Network]\nLinkLocalAddressing=no\n' | sudo tee /etc/systemd/network/25-quicklab-veth1.network >/dev/null
  sudo networkctl reload; sleep 3; ip -br addr show veth0 | sed 's/^/   /'
}
install_kolla() {
  python3 -m venv "$VENV"
  "${PX[@]}" "$VENV/bin/pip" install -q -U pip
  # docker and dbus-python in the venv too: on an all-in-one, Ansible runs the venv's Python for localhost.
  "${PX[@]}" "$VENV/bin/pip" install -q "ansible-core==$ANSIBLE_CORE_VERSION" "kolla-ansible==$KOLLA_ANSIBLE_VERSION" docker dbus-python
  "${PX[@]}" "$VENV/bin/kolla-ansible" install-deps > "$M/install-deps.log" 2>&1 || { tail -5 "$M/install-deps.log"; return 1; }
  echo "   $("$VENV/bin/kolla-ansible" --version), ansible-core $ANSIBLE_CORE_VERSION"
}
configure() {
  sudo mkdir -p /etc/kolla/config && sudo chown -R "$USER": /etc/kolla
  cp "$VENV"/share/kolla-ansible/etc_examples/kolla/* /etc/kolla/
  cp "$VENV/share/kolla-ansible/ansible/inventory/all-in-one" "$INV"
  "$VENV/bin/kolla-genpwd"
  local virt=qemu; [ -e /dev/kvm ] && grep -qE 'vmx|svm' /proc/cpuinfo && virt=kvm
  {
    echo "---"
    echo "# openstack-quick-lab: all-in-one. Generated by remote-deploy.sh."
    echo 'kolla_base_distro: "ubuntu"'
    echo 'kolla_container_engine: "docker"'
    echo '# One node: no HAProxy, no keepalived, and no ProxySQL (it would take port 3306 from MariaDB).'
    echo 'enable_haproxy: "no"'
    echo 'enable_proxysql: "no"'
    echo "kolla_internal_vip_address: \"$ADDR\""
    echo "network_interface: \"$IFACE\""
    echo 'neutron_external_interface: "veth1"'
    echo 'neutron_plugin_agent: "openvswitch"'
    echo "nova_compute_virt_type: \"$virt\""
    echo 'docker_client_timeout: 600'
    if [ -n "$DOCKER_REGISTRY" ]; then
      echo "docker_registry: \"$DOCKER_REGISTRY\""; echo 'docker_registry_insecure: true'
      [ -n "$OPENSTACK_TAG" ] && echo "openstack_tag: \"$OPENSTACK_TAG\""
    fi
    if [ -n "$HTTPS_PROXY" ]; then
      echo "docker_http_proxy: \"$HTTPS_PROXY\""; echo "docker_https_proxy: \"$HTTPS_PROXY\""; echo "docker_no_proxy: \"$NOPX\""
      echo 'docker_apt_key_env:'; echo "  http_proxy: \"$HTTPS_PROXY\""; echo "  https_proxy: \"$HTTPS_PROXY\""
      echo "container_http_proxy: \"$HTTPS_PROXY\""; echo "container_https_proxy: \"$HTTPS_PROXY\""; echo "container_no_proxy: \"$NOPX\""
    fi
  } > /etc/kolla/globals.yml
  # Neutron must know the MTU of the cloud's network (often less than 1500 on a cloud).
  printf '[DEFAULT]\nglobal_physnet_mtu = %s\n' "$MTU" > /etc/kolla/config/neutron.conf
  echo "   interface $IFACE ($ADDR, MTU $MTU), nova_compute_virt_type $virt"
}
bootstrap() {
  kolla bootstrap-servers
  # Docker must run with its proxy before the first pull: check the daemon itself, not only its configuration.
  if [ -n "$HTTPS_PROXY" ] && ! sudo docker info 2>/dev/null | grep -q 'HTTPS Proxy'; then
    echo "   Docker is not using its proxy yet: restarting it"; sudo systemctl daemon-reload; sudo systemctl restart docker
    sudo docker info 2>/dev/null | grep -q 'HTTPS Proxy' || { echo "Docker still has no proxy"; return 1; }
  fi
}
# The images on quay.io/openstack.kolla are published for testing: Kolla-Ansible 2026.1 prechecks refuse them
# unless told so. A lab is exactly that use; with your own registry the option is not needed.
prechecks()  { if [ -z "$DOCKER_REGISTRY" ]; then kolla prechecks --use-test-images; else kolla prechecks; fi; }
pull()       { kolla pull; }
deploy()     { kolla deploy; }
postdeploy() { kolla post-deploy; "${PX[@]}" "$VENV/bin/pip" install -q python-openstackclient; }
smoke_test() {
  # shellcheck source=/dev/null
  . /etc/kolla/admin-openrc.sh; export PATH="$VENV/bin:$PATH"
  # init-runonce (Kolla-Ansible's demo set-up: CirrOS image, flavors, demo and external networks) runs only once
  openstack network show public1 >/dev/null 2>&1 || "${PX[@]}" env no_proxy="$ADDR,localhost,127.0.0.1" DEMO_NET_CIDR=10.98.0.0/24 DEMO_NET_GATEWAY=10.98.0.1 \
    EXT_NET_CIDR="$LAB_EXT_CIDR" EXT_NET_RANGE="start=$EXT_START,end=$EXT_END" EXT_NET_GATEWAY="$EXT_GW" \
    "$VENV/share/kolla-ansible/init-runonce" > "$M/init-runonce.log" 2>&1 || { tail -5 "$M/init-runonce.log"; return 1; }
  # The test instance (reused if this step is run again) and its floating IP
  openstack server show demo1 >/dev/null 2>&1 || openstack server create --image cirros --flavor m1.tiny --key-name mykey --network demo-net --wait demo1 -f value -c status
  local fip; fip=$(openstack floating ip list --port "$(openstack port list --server demo1 -f value -c ID | head -1)" -f value -c "Floating IP Address" | head -1)
  if [ -z "$fip" ]; then fip=$(openstack floating ip create public1 -f value -c floating_ip_address); openstack server add floating ip demo1 "$fip"; fi
  echo "   demo1 on floating IP $fip"
  for _ in $(seq 1 30); do ping -c 1 -W 2 "$fip" >/dev/null && break; sleep 5; done
  ping -c 3 "$fip" | tail -2 | sed 's/^/   /'
  # CirrOS starts its SSH server a little after it answers ping: retry for up to 3 minutes
  for _ in $(seq 1 18); do
    ssh -i ~/.ssh/id_ecdsa -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o BatchMode=yes -o ConnectTimeout=10 "cirros@$fip" 'echo "   SSH into demo1: $(hostname)"' 2>/dev/null && return 0
    sleep 10
  done
  echo "   SSH into demo1 failed"; return 1
}

T0=$(date +%s)
step prepare    "Prepare the host"                   prepare_host
step kolla      "Install Kolla-Ansible"              install_kolla
step configure  "Write the configuration"            configure
step bootstrap  "kolla-ansible bootstrap-servers"    bootstrap
step prechecks  "kolla-ansible prechecks"            prechecks
step pull       "kolla-ansible pull"                 pull
step deploy     "kolla-ansible deploy"               deploy
step postdeploy "kolla-ansible post-deploy, client"  postdeploy
step smoke      "Smoke test: an instance, a floating IP, ping and SSH" smoke_test
echo "== OpenStack is ready ($(( $(date +%s)-T0 )) s for this run). On the VM: source ~/kolla-venv/bin/activate; . /etc/kolla/admin-openrc.sh"
for s in prepare kolla configure bootstrap prechecks pull deploy postdeploy smoke; do printf '%-11s %5s s\n' "$s" "$(cat "$M/done-$s" 2>/dev/null || echo -)"; done
